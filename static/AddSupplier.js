/* ==========================================================
   SAME ADDRESS
========================================================== */

function copyRegisteredAddress() {

    const checked = $("sameAddress").checked;

    const fields = [
        ["registeredAddress1", "communicationAddress1"],
        ["registeredAddress2", "communicationAddress2"],
        ["registeredCity", "communicationCity"],
        ["registeredState", "communicationState"],
        ["registeredPostal", "communicationPostal"]
    ];

    fields.forEach(([source, target]) => {

        $(target).value = checked
            ? $(source).value
            : "";
    });
}


/* ==========================================================
   KEEP COMMUNICATION ADDRESS UPDATED
========================================================== */

function bindAddressSync() {

    const ids = [
        "registeredAddress1",
        "registeredAddress2",
        "registeredCity",
        "registeredState",
        "registeredPostal"
    ];

    ids.forEach(id => {

        $(id).addEventListener("input", () => {

            if ($("sameAddress").checked) {
                copyRegisteredAddress();
            }

        });

    });
}


