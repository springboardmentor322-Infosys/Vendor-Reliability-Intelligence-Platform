/* ==========================================================
   BUILD PAYLOAD
========================================================== */

function buildSupplierPayload() {

    const phoneCountry = $("phoneCountry").value;

    const phoneNumber = $("phone").value.trim();

    const fullPhone =
        `${phoneCountry}${phoneNumber}`;


    const communicationHasData =
        $("communicationAddress1").value.trim() ||
        $("communicationAddress2").value.trim() ||
        $("communicationCity").value.trim() ||
        $("communicationState").value.trim() ||
        $("communicationPostal").value.trim();


    return {

        supplier_name:
            $("supplierName").value.trim(),

        country:
            $("country").value,

        email:
            $("email").value.trim(),

        phone:
            fullPhone,

        business_type:
            $("supplierType").value || null,

        category:
            $("industry").value || null,

        business: {

            legal_entity_name:
                $("legalEntityName").value.trim() || null,

            website:
                $("website").value.trim() || null,

            tax_id_gst:
                $("taxId").value.trim() || null,

            industry:
                $("industry").value || null,

            supplier_type:
                $("supplierType").value || null,

            duns_number:
                $("dunsNumber").value.trim() || null,

            year_established:
                $("yearEstablished").value
                    ? Number($("yearEstablished").value)
                    : null,

            preferred_language:
                $("preferredLanguage").value || null,

            currency:
                $("currency").value || null
        },

        registered_address: {

            address_type: "Registered",

            address_line1:
                $("registeredAddress1").value.trim(),

            address_line2:
                $("registeredAddress2").value.trim() || null,

            city:
                $("registeredCity").value.trim(),

            state_province:
                $("registeredState").value.trim(),

            postal_code:
                $("registeredPostal").value.trim(),

            country:
                $("country").value,

            phone:
                fullPhone,

            email:
                $("email").value.trim(),

            is_primary: true
        },

        communication_address:
            communicationHasData
                ? {

                    address_type: "Communication",

                    address_line1:
                        $("communicationAddress1").value.trim(),

                    address_line2:
                        $("communicationAddress2").value.trim() || null,

                    city:
                        $("communicationCity").value.trim(),

                    state_province:
                        $("communicationState").value.trim(),

                    postal_code:
                        $("communicationPostal").value.trim(),

                    country:
                        $("country").value,

                    phone:
                        fullPhone,

                    email:
                        $("email").value.trim(),

                    is_primary: false

                }
                : null,

        contacts: [],

        bank_accounts: []
    };
}


/* ==========================================================
   VALIDATION
========================================================== */

function validateSupplierForm() {

    const form = $("supplierForm");

    if (!form.checkValidity()) {

        form.reportValidity();

        return false;
    }

    const year =
        $("yearEstablished").value;

    if (year) {

        const currentYear =
            new Date().getFullYear();

        if (
            Number(year) < 1800 ||
            Number(year) > currentYear
        ) {

            showToast(
                `Year established must be between 1800 and ${currentYear}.`,
                false
            );

            return false;
        }
    }

    return true;
}


/* ==========================================================
   SAVE SUPPLIER
========================================================== */

async function saveSupplier(isDraft = false) {

    if (!validateSupplierForm()) {
        return;
    }

    const payload =
        buildSupplierPayload();

    const button =
        isDraft
            ? $("draftBtn")
            : $("continueBtn");

    const oldText =
        button.innerHTML;

    button.disabled = true;

    button.innerHTML =
        `<i class="fa-solid fa-spinner fa-spin"></i> Saving...`;

    try {

        const result = await apiFetch(
            "/api/suppliers/full",
            {
                method: "POST",

                body: JSON.stringify({
                    ...payload,
                    save_as_draft: isDraft
                })
            }
        );


        savedVendorId =
            result.vendor_id ||
            result.supplier?.vendor_id;


        $("supplierCode").value =
            savedVendorId || "Generated";


        $("overviewStatus").textContent =
            isDraft
                ? "Draft saved"
                : "Saved";


        if (result.supplier) {

            $("overviewName").textContent =
                result.supplier.vendor_name ||
                payload.supplier_name;
        }


        $("poCount").textContent =
            result.summary?.purchase_orders ?? 0;

        $("shipmentCount").textContent =
            result.summary?.shipments ?? 0;

        $("itemCount").textContent =
            result.summary?.items ?? 0;

        $("spendAmount").textContent =
            formatCurrency(
                result.summary?.spend ?? 0,
                payload.business.currency || "USD"
            );


        showToast(
            isDraft
                ? "Supplier draft saved successfully."
                : "Supplier created successfully."
        );


        if (!isDraft) {

            setTimeout(() => {

                /*
                   Change this later to:
                   /add-supplier/business?vendor_id=...
                   when Step 2 is implemented.
                */

                window.location.href =
                    `/suppliers?vendor_id=${encodeURIComponent(savedVendorId)}`;

            }, 1000);
        }

    }
    catch (error) {

        console.error(error);

        showToast(
            error.message ||
            "Unable to save supplier.",
            false
        );

    }
    finally {

        button.disabled = false;

        button.innerHTML =
            oldText;
    }
}


/* ==========================================================
   FORMAT CURRENCY
========================================================== */

function formatCurrency(amount, currency) {

    try {

        return new Intl.NumberFormat(
            "en-US",
            {
                style: "currency",
                currency: currency || "USD"
            }
        ).format(Number(amount || 0));

    }
    catch {

        return `$${Number(amount || 0).toFixed(2)}`;
    }
}


/* ==========================================================
   EVENT SETUP
========================================================== */

function setupEvents() {

    $("supplierForm").addEventListener(
        "submit",
        event => {

            event.preventDefault();

            saveSupplier(false);
        }
    );


    $("draftBtn").addEventListener(
        "click",
        () => saveSupplier(true)
    );


    $("cancelBtn").addEventListener(
        "click",
        () => {

            if (
                confirm(
                    "Discard this supplier form?"
                )
            ) {

                window.location.href =
                    "/suppliers";
            }
        }
    );


    $("sameAddress").addEventListener(
        "change",
        copyRegisteredAddress
    );


    $("supplierName").addEventListener(
        "input",
        updateOverview
    );


    bindAddressSync();

    generateSupplierCode();
}


